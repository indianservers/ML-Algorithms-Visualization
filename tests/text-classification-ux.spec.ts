import { test, expect } from '@playwright/test';
test('train, classify, inspect and edit text on mobile', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://localhost:3355/ml/nlp/text-classification?tab=train');
  await expect(page.getByRole('heading',{name:'Test a sentence'})).toBeVisible();
  await page.getByRole('button',{name:'Unfamiliar',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Insufficient learned evidence'})).toBeVisible();
  await page.getByLabel('Your text').fill('Chipmakers announced a smaller transistor.');
  await page.getByRole('button',{name:'Classify text',exact:true}).click();
  await expect(page.locator('.text-prediction h2')).toHaveText('technology');
  await page.locator('.text-tokens button').first().click();
  await expect(page.locator('.text-token-detail')).toBeVisible();
  await page.locator('.text-mobile-dock').getByRole('button',{name:'Train model'}).click();
  await expect(page.locator('.text-status')).toHaveText('Trained by you');
  await page.locator('.text-mobile-dock').getByRole('button',{name:'Examples',exact:true}).click();
  await page.getByText('Edit 8 examples',{exact:true}).click();
  await page.getByLabel('Example 1 text',{exact:true}).fill('');
  await expect(page.getByRole('alert')).toContainText('text and class are required');
  await expect(page.locator('.text-mobile-dock').getByRole('button',{name:'Train model'})).toBeDisabled();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
});
test('CSV mapping, class management and matrix filtering', async ({page}) => {
  await page.goto('http://localhost:3355/ml/nlp/text-classification?tab=inference');
  await expect(page).toHaveURL(/tab=train/);
  await page.locator('#text-examples > summary').click();
  await page.getByText('Import CSV',{exact:true}).click();
  await page.getByLabel('Upload CSV').setInputFiles({name:'topics.csv',mimeType:'text/csv',buffer:Buffer.from('sentence,topic\n"red apple, ripe",fruit\ngreen pear,fruit\nblue car,vehicle\nyellow truck,vehicle')});
  await expect(page.getByText('4 examples · preview')).toBeVisible();
  await page.getByRole('button',{name:'Use imported examples'}).click();
  await page.locator('.text-training').getByRole('button',{name:'Train model',exact:true}).click();
  await expect(page.locator('.text-status')).toHaveText('Trained by you');
  await page.locator('.text-matrix tbody button').first().click();
  await expect(page.getByRole('button',{name:/Clear filter:/})).toBeVisible();
  await page.getByText('Manage classes',{exact:true}).click();
  await page.getByLabel('Choose class',{exact:true}).selectOption('fruit');
  await page.getByLabel('Rename to').fill('produce');
  await page.getByRole('button',{name:'Rename class',exact:true}).click();
  await expect(page.locator('.text-status')).toHaveText('Changes pending');
  await expect(page.locator('.text-distribution')).toContainText('produce');
});
