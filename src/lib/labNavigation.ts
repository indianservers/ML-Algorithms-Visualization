export function resolveNavRoute(label: string): string | undefined {
  return NAV_ROUTES[normalizeNavLabel(label)];
}

export function useLabNavigate() {
  const navigate = useNavigate();
  return useCallback(
    (label: string) => {
      const route = resolveNavRoute(label);
      if (!route) return false;
      navigate(route);
      return true;
    },
    [navigate],
  );
}
