export function normalizeNavLabel(raw: string): string {
  return raw
    .replace(/\s+(opened|selected)$/i, "")
    .replace(/^[\d]+[.)]\s+/u, "")
    .replace(/[?]/g, "")
    .replace(/\s*&\s*/g, " ")
    .replace(/^[^A-Za-z0-9]+/u, "")
    .replace(/\s*[›▾⌄⌃●·]+$/u, "")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

