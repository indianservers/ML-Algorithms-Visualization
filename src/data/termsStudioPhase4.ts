import type { TermLesson } from './termsStudio';

function term(item: Omit<TermLesson, 'workedExample' | 'tryThis' | 'whenToUse' | 'watchFor' | 'analogy' | 'hook' | 'explanation'> & {
  explanation?: string[];
  tryThis?: string[];
  whenToUse?: string;
  watchFor?: string;
  analogy?: string;
}): TermLesson {
  const blurb = item.blurb;
  return {
    analogy: item.analogy ?? blurb,
    hook: blurb,
    explanation: item.explanation ?? [blurb],
    workedExample: {
      title: item.label,
      setup: blurb,
      steps: item.explanation?.slice(0, 3) ?? [blurb],
      takeaway: blurb,
    },
    tryThis: item.tryThis ?? ['Move one control and say what changed in one sentence.'],
    whenToUse: item.whenToUse ?? blurb,
    watchFor: item.watchFor ?? 'Keep this page small: one idea, one picture.',
    ...item,
  };
}

